#!/usr/bin/env node
// Regenerates docs/SERVERS.md from each servers/<name>/config.json and README blurbs.
// Run from repo root: npm run docs:servers
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const serversDir = join(root, 'servers');
const outPath = join(root, 'docs', 'SERVERS.md');

/** Provider id (folder without -mcp) → category heading */
const CATEGORY_BY_ID = {
  'open-meteo': 'Weather & environment',
  'usgs-earthquake': 'Weather & environment',
  'sunrise-sunset': 'Weather & environment',
  'opensky': 'Weather & environment',
  nominatim: 'Weather & environment',
  'rest-countries': 'Geography & places',
  worldbank: 'Geography & places',
  worldtime: 'Geography & places',
  wikipedia: 'Reference & knowledge',
  wikidata: 'Reference & knowledge',
  dictionary: 'Reference & knowledge',
  datamuse: 'Reference & knowledge',
  mdn: 'Reference & knowledge',
  trivia: 'Reference & knowledge',
  'hacker-news': 'News & community',
  stackexchange: 'News & community',
  arxiv: 'Research & science',
  openalex: 'Research & science',
  pubmed: 'Research & science',
  crossref: 'Research & science',
  'semantic-scholar': 'Research & science',
  gbif: 'Research & science',
  openfda: 'Research & science',
  'open-library': 'Books & media',
  musicbrainz: 'Books & media',
  tvmaze: 'Books & media',
  jikan: 'Books & media',
  pokeapi: 'Books & media',
  swapi: 'Books & media',
  'npm-registry': 'Developer tools',
  pypi: 'Developer tools',
  'github-public': 'Developer tools',
  frankfurter: 'Finance & data',
  spacex: 'Science & space',
  opennotify: 'Science & space',
  openfoodfacts: 'Health & lifestyle',
  careclinic: 'Health & lifestyle',
};

function folderToId(folder) {
  return folder.replace(/-mcp$/, '');
}

function extractBlurb(readme) {
  const lines = readme.split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line || line.startsWith('#')) continue;
    return line.replace(/\s+/g, ' ');
  }
  return '';
}

function envNote(folder, id) {
  if (id === 'careclinic') {
    return ' — requires `CARECLINIC_BEARER_TOKEN` in the MCP process env';
  }
  if (id === 'semantic-scholar') {
    return ' — optional `SEMANTIC_SCHOLAR_API_KEY`';
  }
  if (id === 'github-public') {
    return ' — unauthenticated GitHub (~60 req/hr)';
  }
  return '';
}

const entries = [];

for (const folder of readdirSync(serversDir).sort()) {
  if (folder === 'unified-mcp') continue;
  const dir = join(serversDir, folder);
  const configPath = join(dir, 'config.json');
  const readmePath = join(dir, 'README.md');
  if (!existsSync(configPath)) continue;

  const config = JSON.parse(readFileSync(configPath, 'utf8'));
  const port = config.mcp?.httpPort;
  const id = folderToId(folder);
  let blurb = '';
  if (existsSync(readmePath)) {
    blurb = extractBlurb(readFileSync(readmePath, 'utf8'));
  }
  const category = CATEGORY_BY_ID[id] ?? 'Other';
  entries.push({
    folder,
    id,
    port,
    blurb,
    category,
    inUnified: id === 'careclinic' ? 'optional (env)' : 'yes',
    envNote: envNote(folder, id),
  });
}

const byCategory = new Map();
for (const e of entries) {
  if (!byCategory.has(e.category)) byCategory.set(e.category, []);
  byCategory.get(e.category).push(e);
}

const categoryOrder = [
  'Weather & environment',
  'Geography & places',
  'Reference & knowledge',
  'News & community',
  'Research & science',
  'Books & media',
  'Developer tools',
  'Finance & data',
  'Science & space',
  'Health & lifestyle',
  'Other',
];

const lines = [
  '# Server catalog',
  '',
  `Generated by \`npm run docs:servers\` on ${new Date().toISOString().slice(0, 10)}.`,
  '',
  `${entries.length} API servers (plus [unified-mcp](../servers/unified-mcp/) on port 8000).`,
  '',
  'Most APIs need **no API key**. Exceptions are called out below. For credential-backed integrations, pass variables in your **MCP client config** (`env` block) — unified-mcp only exposes those tools when the variable is present in the server process.',
  '',
];

for (const cat of categoryOrder) {
  const list = byCategory.get(cat);
  if (!list?.length) continue;
  lines.push(`## ${cat}`, '');
  lines.push('| Server | Port | In unified | Summary |');
  lines.push('|--------|------|------------|---------|');
  for (const e of list.sort((a, b) => a.folder.localeCompare(b.folder))) {
    const link = `[${e.folder}](../servers/${e.folder}/)`;
    const summary = (e.blurb + e.envNote).replace(/\|/g, '\\|');
    lines.push(`| ${link} | ${e.port ?? '—'} | ${e.inUnified} | ${summary} |`);
  }
  lines.push('');
}

lines.push(
  '## Running one server',
  '',
  '```bash',
  'npx turbo run start:http --filter=<folder-name>   # e.g. open-meteo-mcp',
  '```',
  '',
  'Or `cd servers/<folder-name>` and `npm run start:http`. HTTP ports are in each `config.json`.',
  ''
);

writeFileSync(outPath, lines.join('\n'));
console.error(`Wrote ${outPath} (${entries.length} servers)`);
